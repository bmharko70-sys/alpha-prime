export const MOLECULES_BY_FORMULA: Record<string, MoleculeData> = Object.fromEntries(
  MOLECULES.map((m) => [m.formula, m]),
)

export function searchMolecules(query: string): MoleculeData[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return MOLECULES.filter(
    (m) => m.name.toLowerCase().includes(q) || m.formula.toLowerCase().includes(q.replace(/\s/g, "")),
  ).slice(0, 20)
}
